#!/usr/bin/env python3
"""Sidebar Press: build Fantasy Grounds Unity NPC import text for every creature note.

Reads each statblock callout (> [!example]+ Name (CR ...)) in 65-Bestiary and writes a
"## FGU Import" section at the end of the note, with plain text ready to paste into
FGU's NPCs > Import Text (mode: 2022 - Monsters of the Multiverse, the 2014-style layout).
Re-run after any statblock change; the section is regenerated, never hand-edited.

Usage: python3 fgu_import.py "<vault>/65-Bestiary"
"""
import os, re, sys, glob

PB = {0:2,1:2,2:2,3:2,4:2,5:3,6:3,7:3,8:3,9:4,10:4,11:4,12:4,13:5,14:5,15:5,16:5,17:6,18:6,19:6,20:6,21:7,22:7,23:7,24:7,25:8,26:8,27:8,28:8,29:9,30:9}
HEADINGS = {"Actions", "Bonus Actions", "Reactions", "Legendary Actions", "Lair Actions"}
SKIP_TITLES = ("Applying the Template", "(haunt", "Regional Effects")
SECTION = "## FGU Import"

BONE_BEAST = ("Pack-Bound. The beast obeys whoever wears or carries its pack's binding relic. With no one holding the relic, "
              "it hunts the relic, guards its maker's tomb, and drags carrion home.\n"
              "Binding Law. The pack was made under one law its beasts can't break (DM's choice, e.g. never attack a creature "
              "standing in running water).")

def plain(s):
    s = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", s)
    s = re.sub(r"\[\[([^\]]+)\]\]", r"\1", s)
    s = s.replace("***", "").replace("**", "")
    s = re.sub(r"(?<![\w*])\*([^*]+)\*(?![\w*])", r"\1", s)   # *italics*
    s = s.replace("−", "-").replace("–", "-").replace("—", "-")  # minus, en dash, em dash
    s = s.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    s = s.replace("×", "x")
    return re.sub(r"[ \t]+", " ", s).strip()

def callouts(text):
    """Yield (title, [body lines]) for every [!example] callout."""
    lines = text.split("\n"); i = 0
    while i < len(lines):
        m = re.match(r"^> \[!example\][+-]? (.*)$", lines[i])
        if m:
            title, body = m.group(1), []
            i += 1
            while i < len(lines) and lines[i].startswith(">"):
                body.append(lines[i][1:].lstrip(" ") if lines[i] != ">" else ""); i += 1
            yield title, body
        else:
            i += 1

def cr_value(title):
    m = re.search(r"\(CR ([0-9/]+)", title)
    if not m: return None
    c = m.group(1)
    return 0 if "/" in c else int(c)

def convert(title, body, lair=None):
    name = title.split(" (CR")[0].strip()
    out = [plain(name)]
    pb = PB.get(cr_value(title) or 0, 2)
    for raw in body:
        if not raw.strip(): continue
        if raw.startswith("|"):
            cells = [c.strip() for c in raw.strip("|").split("|")]
            if all(re.fullmatch(r":?-+:?", c) for c in cells): continue
            out.append(plain(" ".join(cells))); continue
        if "See [[Bone Beast Template]]" in raw:
            out.extend(BONE_BEAST.split("\n")); continue
        line = plain(raw)
        if line in HEADINGS:
            out.append(line); continue
        if " · " in raw:                      # "**AC** x · **HP** y" rows
            for part in raw.split(" · "):
                p = plain(part)
                p = re.sub(r"^Vulnerabilities\b", "Damage Vulnerabilities", p)
                p = re.sub(r"^Immunities\b", "Damage Immunities", p)
                p = re.sub(r"^AC\b", "Armor Class", p); p = re.sub(r"^HP\b", "Hit Points", p)
                if p.startswith("Challenge"): p += f" Proficiency Bonus +{pb}"
                out.append(p)
            continue
        line = re.sub(r"^AC\b", "Armor Class", line); line = re.sub(r"^HP\b", "Hit Points", line)
        if line.startswith("Challenge"): line += f" Proficiency Bonus +{pb}"
        out.append(line)
    if lair:
        out.append("Lair Actions")
        for raw in lair:
            if not raw.strip(): continue
            out.append(plain(re.sub(r"^- ", "", raw)))
    return "\n".join(out)

def build(path):
    text = open(path, encoding="utf-8").read()
    if "\ntype: creature\n" not in text: return None
    blocks, lair = [], None
    for title, body in callouts(text):
        if "Lair Actions" in title: lair = body; continue
        if any(s in title for s in SKIP_TITLES) or "(CR" not in title: continue
        blocks.append((title, body))
    if not blocks: return None
    texts = []
    for n, (t, b) in enumerate(blocks):
        texts.append(convert(t, b, lair if n == 0 else None))
    sec = [SECTION, "",
           "Paste each block into Fantasy Grounds Unity: **NPCs → Import Text**, mode **2022 – Monsters of the Multiverse** "
           "(the 2014-style layout). Spells link only if a module containing them is open in the campaign. "
           "If a field comes in blank, check the NPC's Notes tab, which shows where parsing stopped. "
           "*Generated by `70-Company/Tools/fgu_import.py`; re-run it after any statblock change rather than editing by hand.*", ""]
    stem = os.path.basename(path)[:-3]; A = "99-Assets/SP-BST-01"
    sec += ["> [!art]- FGU Portrait & Token", f"> ![[{A}/portraits/{stem} \u2014 Portrait.png|300]] ![[{A}/tokens/{stem} \u2014 Token.png|140]]", ""]
    for t in texts:
        sec += ["```text", t, "```", ""]
    body = text.split("\n" + SECTION + "\n")[0].rstrip("\n")
    open(path, "w", encoding="utf-8").write(body + "\n\n" + "\n".join(sec).rstrip("\n") + "\n")
    return len(texts)

if __name__ == "__main__":
    d = sys.argv[1]
    for p in sorted(glob.glob(os.path.join(d, "*.md"))):
        n = build(p)
        print(f"{os.path.basename(p)}: {n if n else 'skipped'}")
